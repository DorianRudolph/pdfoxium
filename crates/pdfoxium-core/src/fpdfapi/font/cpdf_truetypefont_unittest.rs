fn make_font(
    doc: &CpdfDocument,
    font_data: &[u8],
    mapper: &mut CfxFontMapper,
) -> Option<CpdfLoadedSimpleFont> {
    let font_file_stream = retain_object(CpdfStream::from_data_and_dict(
        font_data.to_vec(),
        retain_object(CpdfDictionary::new()),
    ));
    doc.holder()
        .borrow_mut()
        .add_indirect_object(font_file_stream.clone());
    let font_file_stream_object_number = font_file_stream.borrow().obj_num();
    assert!(font_file_stream_object_number > 0);
    let font_file_stream_ref = retain_object(CpdfReference::new(
        &doc.holder(),
        font_file_stream_object_number,
    ));
    let mut font_descriptor_dict = CpdfDictionary::new();
    font_descriptor_dict.set_new_name_for(b"Type", b"FontDescriptor");
    font_descriptor_dict.set_for(b"FontFile2", Some(font_file_stream_ref));
    // The MacRoman 0x2E char code to U+01 mapping is intentionally non-standard.
    // Native constructs the byte vector through std::end, including final NUL.
    const kToUnicode: &[u8] = concat!(
        r"
/CIDInit /ProcSet findresource begin
12 dict begin
begincmap
/CIDSystemInfo <<
    /Registry (Adobe)
    /Ordering (UCS)
    /Supplement 0
>> def
/CMapName /Adobe-Identity-UCS def
/CMapType 2 def
1 begincodespacerange
<00><FF>
endcodespacerange
1 beginbfrange
<2E><2E><0001>
endbfrange
endcmap
CMapName currentdict /CMap defineresource pop
end
end",
        "\0"
    )
    .as_bytes();

    let to_unicode_stream = retain_object(CpdfStream::from_data_and_dict(
        kToUnicode.to_vec(),
        retain_object(CpdfDictionary::new()),
    ));
    doc.holder()
        .borrow_mut()
        .add_indirect_object(to_unicode_stream.clone());
    let to_unicode_object_number = to_unicode_stream.borrow().obj_num();
    assert!(to_unicode_object_number > 0);
    let to_unicode_ref = retain_object(CpdfReference::new(&doc.holder(), to_unicode_object_number));
    let mut font_dict = CpdfDictionary::new();
    font_dict.set_new_name_for(b"BaseFont", b"CHEESE+Swiss");
    font_dict.set_new_name_for(b"Type", b"Font");
    font_dict.set_new_name_for(b"Subtype", b"TrueType");
    font_dict.set_new_name_for(b"Encoding", b"MacRomanEncoding");
    font_dict.set_for(b"ToUnicode", Some(to_unicode_ref));
    font_dict.set_for(b"FontDescriptor", Some(retain_object(font_descriptor_dict)));
    CpdfLoadedSimpleFont::load(retain_object(font_dict), doc.page_data(), mapper)
}

#[test]
fn AllUnicodeCmapsTreatedEqually() {
    let _fixture = TestWithPageModule::new();
    // The mapper supplies the global font service owned by the native fixture;
    // keep it alive through both loaded fonts and document teardown.
    let mut mapper = CfxFontMapper::new();
    let doc = CpdfDocument::new();
    let cmap31 = make_font(&doc, &kCmap31Ttf, &mut mapper);
    let cmap03 = make_font(&doc, &kCmap03Ttf, &mut mapper);
    assert!(cmap31.is_some());
    assert!(cmap03.is_some());
    let cmap31 = cmap31.unwrap();
    let cmap03 = cmap03.unwrap();
    let period = 0x2e;
    // Native unused_is_vert is only an out-parameter for the shared font API;
    // this concrete simple-font mapping returns the glyph directly.
    let cmap31_glyph = cmap31.base().glyph_from_char_code(period);
    let cmap03_glyph = cmap03.base().glyph_from_char_code(period);
    assert_eq!(cmap31_glyph, 1);
    assert_eq!(cmap31_glyph, cmap03_glyph);
}
