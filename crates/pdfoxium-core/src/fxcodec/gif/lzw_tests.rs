#[test]
fn create_bad_params() {
    for (color, code) in [(0x10, 2), (4, 15), (2, 2)] {
        assert!(LzwDecompressor::create(color, code).is_none());
    }
}
#[test]
fn extract_data() {
    let mut decoder = LzwDecompressor::create(1, 2).unwrap();
    for size in [0, 5, 20] {
        decoder.decompressed = (0..10).collect();
        let mut dest = [255; 20];
        let count = decoder.extract_data(&mut dest[..size]);
        assert_eq!(count, size.min(10));
        assert_eq!(
            &dest[..count],
            &(0..10).rev().take(count).collect::<Vec<_>>()
        );
        assert!(dest[count..].iter().all(|b| *b == 255));
        assert_eq!(
            decoder.decompressed,
            (0..10 - count as u8).collect::<Vec<_>>()
        );
    }
}
#[test]
fn decode_bad_params() {
    let mut decoder = LzwDecompressor::create(0, 2).unwrap();
    assert_eq!(
        decoder.decode(&[], &mut [0; 10]),
        (LzwStatus::Unfinished, 0, 0)
    );
    assert_eq!(
        decoder.decode(&[0], &mut []).0,
        LzwStatus::InsufficientDestSize
    );
}
#[test]
fn decode1x1_single_colour() {
    let mut decoder = LzwDecompressor::create(0, 2).unwrap();
    let source = &[0x44, 0x01];
    let expected = &[0x00];
    let mut output = vec![255; expected.len()];
    let (status, _, written) = decoder.decode(source, &mut output);
    assert_eq!(status, LzwStatus::Success);
    assert_eq!(written, expected.len());
    assert_eq!(output, expected);
}
