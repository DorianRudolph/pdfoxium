#[test]
fn multiple_decodes() {
    let mut decoder = LzwDecompressor::create(0, 2).unwrap();
    let source = [0x84, 0x6f, 0x05];
    let mut output = [255; 4];
    let (status, used, written) = decoder.decode(&source, &mut output);
    assert_eq!(status, LzwStatus::InsufficientDestSize);
    assert_eq!(written, 4);
    assert_eq!(output, [0; 4]);
    output.fill(255);
    let (status, _, written) = decoder.decode(&source[used..], &mut output);
    assert_eq!(status, LzwStatus::Success);
    assert_eq!(written, 4);
    assert_eq!(output, [0; 4]);
}
