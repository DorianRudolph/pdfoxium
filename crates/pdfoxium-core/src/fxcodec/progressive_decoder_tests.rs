#[test]
fn large_bmp() {
    let mut input = vec![0; 54 + 112 * 38];
    input[..2].copy_from_slice(b"BM");
    input[2..6].copy_from_slice(&4310u32.to_le_bytes());
    input[10..14].copy_from_slice(&54u32.to_le_bytes());
    input[14..18].copy_from_slice(&40u32.to_le_bytes());
    input[18..22].copy_from_slice(&37u32.to_le_bytes());
    input[22..26].copy_from_slice(&38u32.to_le_bytes());
    input[26..28].copy_from_slice(&1u16.to_le_bytes());
    input[28..30].copy_from_slice(&24u16.to_le_bytes());
    input[34..38].copy_from_slice(&4256u32.to_le_bytes());
    input[38..42].copy_from_slice(&2835u32.to_le_bytes());
    input[42..46].copy_from_slice(&2835u32.to_le_bytes());
    for (i, b) in input[54..].iter_mut().enumerate() {
        *b = i as u8;
    }
    assert_eq!(input.len(), 4310);
    let (mut decoder, status) = load(&input, FxcodecImageType::Bmp);
    assert_eq!(status, FxcodecStatus::FrameReady);
    let bitmap = finish(
        &mut decoder,
        37,
        38,
        FxdibFormat::Bgr,
        FxcodecStatus::DecodeFinished,
    );
    for row in 0..38 {
        let bitmap = bitmap.borrow();
        let line = bitmap.scanline(37 - row).unwrap();
        let expected: Vec<u8> = (0..111).map(|col| (row * 112 + col) as u8).collect();
        assert_eq!(&line[..111], expected);
        assert_eq!(line[111], 0);
    }
}
#[test]
fn explicit_bmp_alpha_survives_progressive_and_xfa_image_loading() {
    let mut source = vec![0u8; 126];
    source[..2].copy_from_slice(b"BM");
    for (offset, value) in [
        (2, 126u32),
        (10, 122),
        (14, 108),
        (18, 1),
        (22, 1),
        (30, 3),
        (54, 0x00ff0000),
        (58, 0x0000ff00),
        (62, 0x000000ff),
        (66, 0xff000000),
    ] {
        source[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
    }
    source[26..28].copy_from_slice(&1u16.to_le_bytes());
    source[28..30].copy_from_slice(&32u16.to_le_bytes());
    source[122..].copy_from_slice(&[10, 20, 30, 64]);
    let (mut decoder, status) = load(&source, FxcodecImageType::Bmp);
    assert_eq!(status, FxcodecStatus::FrameReady);
    let bitmap = finish(
        &mut decoder,
        1,
        1,
        FxdibFormat::Bgra,
        FxcodecStatus::DecodeFinished,
    );
    assert_eq!(bitmap.borrow().scanline(0).unwrap(), [10, 20, 30, 64]);
    #[cfg(feature = "xfa")]
    {
        let resource = crate::xfa::fxfa::cxfa_ffimage::load_image_from_buffer(
            Rc::new(CfxReadOnlySpanStream::new(&source)),
            FxcodecImageType::Bmp,
        )
        .unwrap();
        assert_eq!(resource.bitmap.format(), FxdibFormat::Bgra);
        assert_eq!(resource.bitmap.scanline(0).unwrap(), [10, 20, 30, 64]);
        assert_eq!(resource.dpi, (96, 96));
    }
}
