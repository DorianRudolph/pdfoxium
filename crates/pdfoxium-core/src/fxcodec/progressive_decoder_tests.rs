//! Complete native portable fixtures and assertions from progressive_decoder_unittest.cpp.
use super::*;
use crate::fxcrt::cfx_read_only_span_stream::CfxReadOnlySpanStream;
fn load(input: &[u8], kind: FxcodecImageType) -> (ProgressiveDecoder, FxcodecStatus) {
    let mut decoder = ProgressiveDecoder::new();
    let status = decoder.load_image_info(
        Rc::new(CfxReadOnlySpanStream::new(input)),
        kind,
        &mut CfxDibAttribute::default(),
        true,
    );
    (decoder, status)
}
fn finish(
    decoder: &mut ProgressiveDecoder,
    width: i32,
    height: i32,
    format: FxdibFormat,
    expected: FxcodecStatus,
) -> Rc<RefCell<CfxDibitmap>> {
    assert_eq!(decoder.width(), width);
    assert_eq!(decoder.height(), height);
    assert_eq!(decoder.get_bitmap_format(), format);
    assert_eq!(decoder.get_frames(), (FxcodecStatus::DecodeReady, 1));
    let bitmap = Rc::new(RefCell::new(
        CfxDibitmap::create(width, height, format, 0).unwrap(),
    ));
    let mut status = decoder.start_decode(bitmap.clone());
    while status == FxcodecStatus::DecodeToBeContinued {
        status = decoder.continue_decode();
    }
    assert_eq!(status, expected);
    bitmap
}
