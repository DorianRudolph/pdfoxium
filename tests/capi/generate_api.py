#!/usr/bin/env python3
"""Generate the shared C++ API table from the reviewed public-header inventory.

The generated member declarations use decltype(&::name) in api.h, preserving
PDFium's public signatures and calling conventions without copying them here.
"""

import argparse
import contextlib
import importlib.util
import io
from pathlib import Path
import sys

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[2]
INVENTORY_PATH = ROOT / "scripts/audit-capi-tests.py"
SPEC = importlib.util.spec_from_file_location("capi_inventory", INVENTORY_PATH)
INVENTORY = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(INVENTORY)


def render():
    """Validate the reviewed scope before emitting either include file."""
    # Keep one declaration parser and one explicit exclusion policy. The audit
    # also rejects new/deleted declarations until their scope is reviewed.
    with contextlib.redirect_stdout(io.StringIO()):
        INVENTORY.check()
    functions = INVENTORY.public_functions()
    headers = sorted(INVENTORY.PUBLIC.glob("*.h"))
    banner = "// Generated by tests/capi/generate_api.py; do not edit.\n"
    return {
        "api_headers.inc": banner + "".join(
            f'#include "public/{path.name}"\n' for path in headers
        ),
        "api_functions.inc": banner + "".join(
            f"PDFIUM_API({name})\n"
            for name in functions if name not in INVENTORY.EXCLUDED
        ),
    }


def generate(output_dir):
    files = render()
    output_dir.mkdir(parents=True, exist_ok=True)
    for name, contents in files.items():
        target = output_dir / name
        # Documentation changes do not change the typed API table. Keep
        # unchanged includes intact so those edits do not rebuild every test.
        if target.exists() and target.read_bytes() == contents.encode("utf-8"):
            continue
        with target.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(contents)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True,
                        help="directory for api_headers.inc and api_functions.inc")
    args = parser.parse_args()
    try:
        generate(args.output_dir)
    except (OSError, ValueError) as error:
        print(f"C API table generation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
