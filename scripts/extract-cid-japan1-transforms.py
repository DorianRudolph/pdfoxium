#!/usr/bin/env python3
"""Extract the pinned PDFium Japan1 vertical CID transforms."""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "upstream/pdfium/core/fpdfapi/font/cpdf_cidfont.cpp"
TARGET = ROOT / "crates/pdfoxium-core/src/fpdfapi/font/cpdf_cidfont_japan1.rs"

source = SOURCE.read_text()
body = source.split("constexpr CIDTransform kJapan1VerticalCIDs[] = {", 1)[1].split("};", 1)[0]
rows = re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", body)
assert len(rows) > 100
assert [int(row[0]) for row in rows] == sorted(int(row[0]) for row in rows)
text = [
    "// Generated by scripts/extract-cid-japan1-transforms.py from the pinned PDFium source.",
    "// Copyright 2016 The PDFium Authors",
    "// Use of this source code is governed by a BSD-style license that can be",
    "// found in upstream/pdfium/LICENSE.",
    "// Original code copyright 2014 Foxit Software Inc. http://www.foxitsoftware.com",
    "",
    "use super::cpdf_cidfont::CidTransform;",
    "",
    "pub(super) const JAPAN1_VERTICAL_CIDS: &[CidTransform] = &[",
]
for cid, a, b, c, d, e, f in rows:
    text.append(f"    CidTransform {{ cid: {cid}, a: {a}, b: {b}, c: {c}, d: {d}, e: {e}, f: {f} }},")
text.append("];")
TARGET.write_text("\n".join(text) + "\n")
